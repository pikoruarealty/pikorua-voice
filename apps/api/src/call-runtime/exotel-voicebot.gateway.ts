import { WebSocketGateway, OnGatewayConnection, OnGatewayDisconnect } from "@nestjs/websockets";
import { WebSocket, RawData } from "ws";
import { Injectable, Inject, Logger } from "@nestjs/common";
import type { IncomingMessage } from "http";
import { DeepgramLiveService, type LiveSession } from "../stt/deepgram-live.service";
import { ElevenlabsService } from "../tts/elevenlabs.service";
import { CallRuntimeService } from "./call-runtime.service";
import { CallRepository } from "@pikorua/db";

// Exotel's Voicebot WebSocket carries raw 16-bit linear PCM, 8 kHz, mono,
// little-endian (slin/s16le) in BOTH directions — confirmed against Exotel's
// streaming docs. ElevenLabs "pcm_8000" returns exactly this (headerless raw
// PCM), so Exotel plays it back without transcoding. (ulaw_8000 was wrong:
// µ-law bytes read as linear PCM is structured noise — the crackling.)
const EXOTEL_OUTPUT_FORMAT = "pcm_8000";
const EXOTEL_SAMPLE_RATE = 8000;

// Exotel requires media frames to be a multiple of 320 bytes (20 ms @ 8 kHz,
// 16-bit mono); the recommended frame is ~100 ms (3200 bytes) and a single
// frame must stay ≤ 100 KB. ElevenLabs streams PCM in arbitrary HTTP chunk
// sizes, so we re-frame: accumulate bytes and emit fixed 3200-byte frames,
// padding the final flush with silence (zeros) up to a 320-byte boundary.
const EXOTEL_FRAME_BYTES = 3200; // 100 ms
const EXOTEL_FRAME_ALIGN = 320; // 20 ms — Exotel's required multiple

// One 3200-byte frame is 100 ms of audio. Exotel plays media in real time with
// a small jitter buffer, so frames must be delivered at ~real-time pace — a
// long reply (e.g. a 12 s greeting) generated by TTS in ~1 s would otherwise be
// emitted as a single burst that overflows Exotel's buffer and gets dropped
// (heard as silence). We pace at a slight lead (90 ms) to keep the buffer fed
// without overflowing it.
const EXOTEL_FRAME_PACING_MS = 90;

// Grace period before hanging up after the LAST reply. Because we pace frames
// at a slight lead (90 ms send per 100 ms of audio), our local queue empties
// BEFORE Exotel has finished playing what we already sent — closing the socket
// the instant the queue drains clips the end of Maya's closing line. We wait an
// extra fixed grace so Exotel's buffer plays out fully and her final sentence is
// never cut off. Generous enough to cover any realistic closing statement.
const EXOTEL_HANGUP_GRACE_MS = 9000;

// If the client says nothing for this long, Maya asks if they're still there.
const INACTIVITY_TIMEOUT_MS = 35_000;
// Two consecutive inactivity fires with no real utterance in between → goodbye + hang up.
const INACTIVITY_MAX_STRIKES = 2;

class PcmReframer {
  private buf: Buffer = Buffer.alloc(0);

  constructor(private readonly emit: (frame: Buffer) => void) {}

  push(chunk: Buffer) {
    if (chunk.length === 0) return;
    this.buf = this.buf.length ? Buffer.concat([this.buf, chunk]) : chunk;
    while (this.buf.length >= EXOTEL_FRAME_BYTES) {
      this.emit(this.buf.subarray(0, EXOTEL_FRAME_BYTES));
      this.buf = this.buf.subarray(EXOTEL_FRAME_BYTES);
    }
  }

  // Emit the remaining bytes, padded with PCM silence (0x00) to a 320-byte
  // multiple so Exotel accepts the final partial frame. Called once at the end
  // of a turn; on barge-in/cancel we drop the remainder instead.
  flush() {
    if (this.buf.length === 0) return;
    const remainder = this.buf.length % EXOTEL_FRAME_ALIGN;
    const frame =
      remainder === 0
        ? this.buf
        : Buffer.concat([this.buf, Buffer.alloc(EXOTEL_FRAME_ALIGN - remainder)]);
    this.emit(frame);
    this.buf = Buffer.alloc(0);
  }
}

// Drains queued audio frames to Exotel at ~real-time pace. Without this the
// whole reply is sent in one burst and Exotel drops it; see EXOTEL_FRAME_PACING_MS.
class PacedSender {
  private queue: Buffer[] = [];
  private timer: ReturnType<typeof setTimeout> | null = null;

  constructor(private readonly send: (frame: Buffer) => void) {}

  enqueue(frame: Buffer) {
    this.queue.push(frame);
    this.pump();
  }

  private pump() {
    if (this.timer) return;
    const next = () => {
      const frame = this.queue.shift();
      if (!frame) {
        this.timer = null;
        return;
      }
      this.send(frame);
      this.timer = setTimeout(next, EXOTEL_FRAME_PACING_MS);
    };
    next(); // first frame immediately, then paced
  }

  // Drop everything still queued — used on barge-in and teardown.
  clear() {
    this.queue = [];
    if (this.timer) {
      clearTimeout(this.timer);
      this.timer = null;
    }
  }

  // True while audio is still queued or in flight.
  get active(): boolean {
    return this.queue.length > 0 || this.timer !== null;
  }
}

type ActiveTurn = { controller: AbortController };

type SessionState = {
  callSid: string | null;
  callId: string | null;
  locale: string;
  turnIndex: number;
  stt: LiveSession | null;
  // Serialises turn processing so overlapping utterances stay in order.
  queue: Promise<void>;
  speaking: boolean;
  active: ActiveTurn | null;
  // True only while the FINAL (end-call) statement is playing out. Barge-in is
  // disabled during this window so the caller saying "ok/bye" can't clip Maya's
  // closing line before the call hangs up.
  closing: boolean;
  // Real-time-paced audio sender to Exotel (shared across greeting + turns).
  pacer: PacedSender;
  // Inactivity: fires after INACTIVITY_TIMEOUT_MS with no client utterance.
  inactivityTimer: ReturnType<typeof setTimeout> | null;
  inactivityStrikes: number;
};

// Exotel Voicebot WebSocket gateway.
//
// Exotel opens one WebSocket per call. Events from Exotel:
//   connected  → handshake complete
//   start      → stream begins; carries callSid + custom_parameters
//   media      → base64 linear16 8 kHz audio chunk
//   dtmf       → digit pressed by caller
//   stop       → caller hung up / stream ended
//
// This gateway sends back:
//   media      → base64 pcm_8000 (raw 16-bit linear PCM) audio for the reply
//   mark       → logical milestone (sentence boundary)
//   clear      → discard queued bot audio (barge-in)
@Injectable()
@WebSocketGateway({ path: "/exotel-stream" })
export class ExotelVoicebotGateway implements OnGatewayConnection, OnGatewayDisconnect {
  private readonly logger = new Logger("ExotelVoicebotGateway");
  private readonly sessions = new Map<WebSocket, SessionState>();

  constructor(
    private readonly deepgramLive: DeepgramLiveService,
    private readonly tts: ElevenlabsService,
    private readonly runtime: CallRuntimeService,
    @Inject(CallRepository) private readonly callRepo: CallRepository,
  ) {}

  handleConnection(client: WebSocket, request?: IncomingMessage) {
    // Optional shared-secret guard: set EXOTEL_STREAM_SECRET and include
    // ?token=<secret> in the WebSocket URL configured in the Exotel applet.
    // WebSocket-level auth: Exotel strips query params from wss:// URLs so a
    // shared-secret token in the URL is not reliable. Security is provided by:
    //   1. TLS (wss://) — connection is encrypted in transit
    //   2. callSid DB validation in the "start" event handler — any rogue
    //      connection that can't supply a valid callSid gets no useful response
    //   3. Exotel HMAC signature on all status-callback webhooks
    this.logger.log(`Exotel stream handshake — url=${request?.url ?? ""}`);

    const state: SessionState = {
      callSid: null,
      callId: null,
      locale: "hi-IN",
      turnIndex: 0,
      stt: null,
      queue: Promise.resolve(),
      speaking: false,
      active: null,
      closing: false,
      pacer: new PacedSender((frame) =>
        this.send(client, { event: "media", media: { payload: frame.toString("base64") } }),
      ),
      inactivityTimer: null,
      inactivityStrikes: 0,
    };
    this.sessions.set(client, state);
    this.logger.log("Exotel voicebot connection opened");

    client.on("message", (data: RawData) => {
      try {
        const msg = JSON.parse(data.toString()) as Record<string, unknown>;
        void this.handleEvent(client, state, msg);
      } catch {
        // Non-JSON frames are ignored.
      }
    });
  }

  handleDisconnect(client: WebSocket) {
    const state = this.sessions.get(client);
    if (state) {
      state.active?.controller.abort();
      state.stt?.close();
      state.pacer.clear();
      this.clearInactivityTimer(state);
    }
    this.sessions.delete(client);
    this.logger.log(
      `Exotel voicebot disconnected${state?.callSid ? ` callSid=${state.callSid}` : ""}`,
    );
  }

  private async handleEvent(client: WebSocket, state: SessionState, msg: Record<string, unknown>) {
    switch (String(msg.event ?? "")) {
      case "connected":
        this.logger.log("Exotel stream: connected");
        break;

      case "start": {
        const start = (msg.start ?? {}) as Record<string, unknown>;
        // Exotel sends either call_sid (newer) or callSid (older) field.
        const callSid = String(start.call_sid ?? start.callSid ?? "");
        const custom = (start.custom_parameters ?? start.customParameters ?? {}) as Record<
          string,
          string
        >;

        state.callSid = callSid || null;

        // Prefer callId passed explicitly via the applet's custom parameters so
        // we avoid an extra DB round-trip on every call. Fall back to a lookup
        // by Exotel's CallSid when no explicit mapping is provided.
        if (custom.callId) {
          state.callId = custom.callId;
          if (custom.locale) state.locale = custom.locale;
        } else if (callSid) {
          try {
            const call = await this.callRepo.findByProviderCallSid(callSid);
            if (call) {
              state.callId = call.id;
              if (call.locale) state.locale = call.locale;
            }
          } catch (err) {
            this.logger.warn(`Failed to resolve callId from callSid=${callSid}: ${String(err)}`);
          }
        }

        if (!state.callId) {
          // No DB record yet — use callSid as a stable key so the session
          // still works; the webhook will create the real record shortly.
          state.callId = callSid || `exotel-${Date.now()}`;
          this.logger.warn(
            `No callId resolved for callSid=${callSid} — using fallback key=${state.callId}`,
          );
        }

        this.logger.log(
          `Exotel stream start: callSid=${callSid} callId=${state.callId} locale=${state.locale}`,
        );

        // Warm clip cache and fire opening greeting concurrently.
        void this.runtime.warmCall(state.callId, state.locale);
        void this.sendGreeting(client, state);

        state.stt = this.openSttSession(client, state);
        break;
      }

      case "media": {
        const payload = (msg.media as Record<string, unknown> | undefined)?.payload;
        if (typeof payload === "string" && state.stt) {
          state.stt.sendAudio(Buffer.from(payload, "base64"));
        }
        break;
      }

      case "dtmf": {
        const digit = String((msg.dtmf as Record<string, unknown> | undefined)?.digit ?? "");
        if (digit) {
          this.logger.log(`DTMF digit=${digit} callId=${state.callId}`);
          // DTMF locale selection can be wired here if needed.
        }
        break;
      }

      case "stop":
        this.logger.log(`Exotel stream stop: callId=${state.callId}`);
        state.active?.controller.abort();
        state.stt?.close();
        state.stt = null;
        state.pacer.clear();
        this.clearInactivityTimer(state);
        break;
    }
  }

  private async sendGreeting(client: WebSocket, state: SessionState): Promise<void> {
    if (!state.callId || client.readyState !== WebSocket.OPEN) return;

    const controller = new AbortController();
    state.active = { controller };

    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });

    try {
      const result = await this.runtime.generateGreetingStream(
        state.callId,
        state.locale,
        {
          signal: controller.signal,
          onAudioChunk: (chunk, info) => {
            if (chunk.length > 0) {
              reframer.push(chunk);
            } else if (info.last) {
              this.send(client, { event: "mark", mark: { name: `g${info.sentenceIndex}` } });
            }
          },
          onCancel: () => {
            state.speaking = false;
            state.pacer.clear();
            this.send(client, { event: "clear" });
          },
        },
        { outputFormat: EXOTEL_OUTPUT_FORMAT },
      );

      // Drain the final partial frame only on a clean finish; on barge-in the
      // remainder is intentionally dropped (we already sent "clear").
      if (!result.canceled && !controller.signal.aborted) {
        reframer.flush();
      }
      if (!result.skipped && !result.canceled) {
        state.speaking = false;
      }
    } catch (err) {
      this.logger.error(
        `Greeting failed callId=${state.callId}`,
        err instanceof Error ? err.stack : String(err),
      );
    } finally {
      if (state.active?.controller === controller) state.active = null;
      // Greeting done — start the 15 s inactivity clock waiting for client to speak.
      this.resetInactivityTimer(client, state);
    }
  }

  private openSttSession(client: WebSocket, state: SessionState): LiveSession {
    return this.deepgramLive.openSession(
      state.locale,
      EXOTEL_SAMPLE_RATE,
      {
        onPartial: (text) => this.handlePartial(client, state, text),
        onUtterance: (text) => this.enqueueTurn(client, state, text),
        onError: (message) => {
          this.logger.warn(`STT error callId=${state.callId}: ${message}`);
        },
      },
      { encoding: "linear16" },
    );
  }

  // True while Maya's voice is still going out to the caller. CRUCIAL: a turn's
  // promise resolves when audio is handed to the pacer, NOT when Exotel finishes
  // playing it — the pacer keeps streaming for seconds afterwards. So `active`
  // and `speaking` are both false during that tail; only `pacer.active` reflects
  // that the caller can still hear Maya. Barge-in MUST consider it or late
  // interruptions are missed.
  private isMayaAudible(state: SessionState): boolean {
    return state.active !== null || state.speaking || state.pacer.active;
  }

  // Stop whatever Maya is currently saying: abort the in-flight turn, drop all
  // queued + in-flight audio locally, and tell Exotel to flush its own playback
  // buffer. After this the caller has the floor.
  private stopSpeaking(client: WebSocket, state: SessionState) {
    state.active?.controller.abort();
    state.pacer.clear();
    this.send(client, { event: "clear" });
    state.speaking = false;
  }

  // Server-side barge-in (fast path): the caller starts talking over Maya. A
  // 3-char floor filters 1-2 char noise/echo blips while still catching short
  // interjections ("हाँ", "रुको", "stop", "नहीं"). She goes silent immediately
  // and the completed utterance drives the next turn.
  private handlePartial(client: WebSocket, state: SessionState, text: string) {
    if (state.closing) return; // never interrupt the final closing line
    if (this.isMayaAudible(state) && text.trim().length >= 1) {
      this.logger.log(`Barge-in (partial) callId=${state.callId} — stopping playback`);
      this.stopSpeaking(client, state);
    }
  }

  private enqueueTurn(client: WebSocket, state: SessionState, utterance: string) {
    this.logger.log(`Utterance callId=${state.callId}: "${utterance.slice(0, 60)}"`);
    // Real utterance — reset inactivity so Maya doesn't ask "still there?" mid-conversation.
    state.inactivityStrikes = 0;
    this.resetInactivityTimer(client, state);
    // Reliable barge-in (commit path): a fully-formed caller utterance must stop
    // Maya even if no partial triggered the fast path above — otherwise her old
    // reply keeps playing from the pacer/Exotel buffer and this turn just queues
    // behind it (the bug that made barge-in look broken). Skipped while closing.
    if (!state.closing && this.isMayaAudible(state)) {
      this.logger.log(`Barge-in (utterance) callId=${state.callId} — stopping playback`);
      this.stopSpeaking(client, state);
    }
    state.queue = state.queue.then(async () => {
      if (!state.callId || client.readyState !== WebSocket.OPEN) return;
      await this.runTurn(client, state, utterance);
    });
  }

  private async runTurn(client: WebSocket, state: SessionState, utterance: string) {
    const controller = new AbortController();
    const active: ActiveTurn = { controller };
    state.active = active;
    state.speaking = false;

    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });

    try {
      const result = await this.runtime.processUtteranceStream(
        state.callId!,
        state.turnIndex,
        utterance,
        { locale: state.locale, outputFormat: EXOTEL_OUTPUT_FORMAT },
        {
          signal: controller.signal,
          onAudioChunk: (chunk, info) => {
            if (chunk.length > 0) {
              reframer.push(chunk);
            } else if (info.last) {
              // Sentence boundary — let Exotel track playback progress.
              this.send(client, { event: "mark", mark: { name: `s${info.sentenceIndex}` } });
            }
          },
          onCancel: () => {
            state.speaking = false;
            state.pacer.clear();
            this.send(client, { event: "clear" });
          },
          onEndCall: () => {
            // Lock out barge-in the moment the LLM signals end-call, before TTS
            // audio finishes draining — otherwise a 1-char partial from background
            // noise fires stopSpeaking and clips Maya's closing statement.
            state.closing = true;
          },
        },
      );

      // Drain the final partial frame only on a clean finish; on barge-in the
      // remainder is intentionally dropped (we already sent "clear").
      if (!result.canceled && !controller.signal.aborted) {
        reframer.flush();
      }

      if (!result.waitForMore && !result.canceled) {
        state.stt?.clearBuffer();
        state.turnIndex += 1;
      }

      if (result.endCall) {
        // Lock out barge-in so a caller "ok/bye/thanks" during the closing line
        // can't abort it and hang up mid-sentence.
        state.closing = true;
        this.logger.log(`Call ended callId=${state.callId} — draining final audio`);
        // Let the paced audio fully drain before closing the WebSocket, else
        // the final reply is cut off. Cap the wait so a stuck pacer can't hang.
        await this.waitForPacerDrain(state, 20_000);
        // Our local queue drains slightly ahead of real-time playback, so give
        // Exotel's buffer time to finish playing Maya's last sentence before we
        // hang up — otherwise her closing line gets clipped.
        await new Promise<void>((r) => setTimeout(r, EXOTEL_HANGUP_GRACE_MS));
        try {
          client.close();
        } catch {}
      }
    } catch (err) {
      this.logger.error(
        `Turn failed callId=${state.callId}`,
        err instanceof Error ? err.stack : String(err),
      );
    } finally {
      if (state.active === active) state.active = null;
      // Always clear: on clean finish we never set it false otherwise; on barge-in
      // onCancel already did this, so setting false twice is harmless.
      state.speaking = false;
    }
  }

  // Resolve once the paced sender has flushed all queued audio, or after
  // maxWaitMs as a safety cap so a stalled pacer can never hang call teardown.
  private async waitForPacerDrain(state: SessionState, maxWaitMs: number): Promise<void> {
    const deadline = Date.now() + maxWaitMs;
    while (state.pacer.active && Date.now() < deadline) {
      await new Promise<void>((r) => setTimeout(r, EXOTEL_FRAME_PACING_MS));
    }
  }

  private send(client: WebSocket, payload: Record<string, unknown>) {
    if (client.readyState === WebSocket.OPEN) {
      try {
        client.send(JSON.stringify(payload));
      } catch {}
    }
  }

  private resetInactivityTimer(client: WebSocket, state: SessionState): void {
    if (state.inactivityTimer !== null) {
      clearTimeout(state.inactivityTimer);
      state.inactivityTimer = null;
    }
    if (state.closing) return;
    state.inactivityTimer = setTimeout(
      () => void this.handleInactivity(client, state),
      INACTIVITY_TIMEOUT_MS,
    );
  }

  private clearInactivityTimer(state: SessionState): void {
    if (state.inactivityTimer !== null) {
      clearTimeout(state.inactivityTimer);
      state.inactivityTimer = null;
    }
  }

  private handleInactivity(client: WebSocket, state: SessionState): void {
    state.inactivityTimer = null;
    if (state.closing || client.readyState !== WebSocket.OPEN) return;
    if (this.isMayaAudible(state)) {
      // Maya is mid-reply — re-arm and check again shortly.
      state.inactivityTimer = setTimeout(
        () => void this.handleInactivity(client, state),
        2_000,
      );
      return;
    }
    state.inactivityStrikes += 1;
    const strikes = state.inactivityStrikes;
    const isHindi = state.locale.startsWith("hi") || state.locale.startsWith("gu");

    if (strikes >= INACTIVITY_MAX_STRIKES) {
      // Second strike with no response — say goodbye and hang up.
      const goodbye = isHindi
        ? "लगता है आप अभी available नहीं हैं। हमारे sales expert आपसे personally connect करेंगे। Thank you, namaste."
        : "It seems you are unavailable. Our sales expert will personally reach out to you. Thank you.";
      state.queue = state.queue.then(async () => {
        if (state.inactivityStrikes < strikes || client.readyState !== WebSocket.OPEN) return;
        state.closing = true;
        await this.playDirectTts(state, goodbye);
        await this.waitForPacerDrain(state, 10_000);
        await new Promise<void>((r) => setTimeout(r, EXOTEL_HANGUP_GRACE_MS));
        try { client.close(); } catch {}
      });
    } else {
      // First strike — ask if they're still there.
      const checkIn = isHindi
        ? "Hello? क्या आप अभी भी line पर हैं?"
        : "Hello? Are you still there?";
      state.queue = state.queue.then(async () => {
        // If the client spoke while this was queued, skip it.
        if (state.inactivityStrikes < strikes || state.closing) return;
        if (client.readyState !== WebSocket.OPEN) return;
        await this.playDirectTts(state, checkIn);
      });
      // Re-arm: another 15 s with no response → second strike.
      this.resetInactivityTimer(client, state);
    }
  }

  // Synthesize text directly to the pacer, bypassing the LLM pipeline.
  // Used for inactivity check-ins where no LLM call is needed.
  private async playDirectTts(state: SessionState, text: string): Promise<void> {
    const controller = new AbortController();
    state.active = { controller };
    state.speaking = false;
    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });
    try {
      await this.tts.synthesizeStream(text, {
        languageCode: /[ऀ-ॿ]/.test(text) ? undefined : "en",
        outputFormat: EXOTEL_OUTPUT_FORMAT,
        signal: controller.signal,
        onChunk: (chunk) => {
          if (chunk.length > 0) reframer.push(chunk);
        },
      });
      if (!controller.signal.aborted) reframer.flush();
    } catch {
      // aborted by barge-in or TTS failure — pacer carries whatever was queued
    } finally {
      state.speaking = false;
      if (state.active?.controller === controller) state.active = null;
    }
  }
}
