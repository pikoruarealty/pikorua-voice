// Exotel's Voicebot WebSocket carries raw 16-bit linear PCM, 8 kHz, mono,
// little-endian (slin/s16le) in BOTH directions — confirmed against Exotel's
// streaming docs. ElevenLabs "pcm_8000" returns exactly this (headerless raw
// PCM), so Exotel plays it back without transcoding. (ulaw_8000 was wrong:
// µ-law bytes read as linear PCM is structured noise — the crackling.)
const EXOTEL_OUTPUT_FORMAT = "pcm_8000";
const EXOTEL_SAMPLE_RATE = 8000;

// Exotel requires media frames to be a multiple of 320 bytes (20 ms @ 8 kHz,
// 16-bit mono); the recommended frame is ~100 ms (3200 bytes) and a single
// frame must stay ≤ 100 KB. ElevenLabs streams PCM in arbitrary HTTP chunk
// sizes, so we re-frame: accumulate bytes and emit fixed 3200-byte frames,
// padding the final flush with silence (zeros) up to a 320-byte boundary.
const EXOTEL_FRAME_BYTES = 3200; // 100 ms
const EXOTEL_FRAME_ALIGN = 320; // 20 ms — Exotel's required multiple

// One 3200-byte frame is 100 ms of audio. Exotel plays media in real time with
// a small jitter buffer, so frames must be delivered at ~real-time pace — a
// long reply (e.g. a 12 s greeting) generated by TTS in ~1 s would otherwise be
// emitted as a single burst that overflows Exotel's buffer and gets dropped
// (heard as silence). We pace at a slight lead (90 ms) to keep the buffer fed
// without overflowing it.
const EXOTEL_FRAME_PACING_MS = 90;

// Grace period before hanging up after the LAST reply. Because we pace frames
// at a slight lead (90 ms send per 100 ms of audio), our local queue empties
// BEFORE Exotel has finished playing what we already sent — closing the socket
// the instant the queue drains clips the end of Maya's closing line. We wait an
// extra fixed grace so Exotel's buffer plays out fully and her final sentence is
// never cut off. Generous enough to cover any realistic closing statement.
const EXOTEL_HANGUP_GRACE_MS = 9000;

// If the client says nothing for this long, Maya asks if they're still there.
const INACTIVITY_TIMEOUT_MS = 45_000;
// Two consecutive inactivity fires with no real utterance in between → goodbye + hang up.
const INACTIVITY_MAX_STRIKES = 2;

// Minimum partial-transcript length (chars) that counts as a barge-in. A 1–2
// char floor fires on echo/noise blips (the caller's line carries Maya's own
// audio back with no echo cancellation), making her interrupt herself. Three
// still catches the shortest real interjections ("हाँ", "रुको", "stop", "नहीं").
const BARGE_IN_MIN_CHARS = 3;

// How long a caller may keep talking to a third party (side conversation, with
// no real reply to Maya) before we gracefully bow out and hang up.
const SIDE_CONVERSATION_HANGUP_MS = 35_000;

// Detect the language a caller utterance is in, so the session can follow them
// (Hindi ⇄ English). Devanagari → Hindi; Latin with >=2 words → English (a lone
// English word is often a loanword inside Hindi speech). Null for short/ambiguous
// input (a bare "ok"/"haan") so a single word can't thrash the locale.
function detectSpokenLanguage(text: string): "hi" | "en" | null {
  if (/[ऀ-ॿ]/.test(text)) return "hi";
  const words = text.trim().split(/\s+/).filter(Boolean);
  if (/[a-zA-Z]/.test(text) && words.length >= 2) return "en";
  return null;
}

// Delay before the gateway's post-call BACKSTOP fires for webhook-managed
// (outbound) calls. Long enough that Exotel's `completed` webhook — which
// enqueues immediately and wins via the shared jobId — normally beats it; the
// backstop only runs if that webhook never arrives, so the call still reaches
// the CRM. Post-call is idempotent, so an overlap is harmless.
const POSTCALL_BACKSTOP_DELAY_MS = 120_000;

// --- Inbound Automatic Gain Control (AGC) -----------------------------------
// Exotel delivers the caller's 16-bit PCM at whatever level their handset/line
// produces. A soft-spoken caller arrives as low-amplitude audio, and Deepgram's
// turn-detection VAD + ASR both degrade on quiet input — Maya mishears or drops
// words. The AGC lifts each inbound frame toward a target RMS so quiet callers
// reach a consistent level BEFORE the audio hits STT. Boost-only (already-loud
// callers pass through near 1×), with a noise gate so line hiss isn't amplified
// into phantom speech. CRITICAL: the gain is PEAK-LIMITED — it is capped per frame
// so the loudest sample never crosses the ceiling, guaranteeing the boosted signal
// never clips. (An earlier version hard-clamped overshoots to ±32767, which
// flat-topped soft-caller peaks into square-wave distortion and GARBLED the STT —
// "Four" heard as "Ford", Hindi turned to mush.) Kill-switch: STT_INBOUND_AGC=0.
// Parse a positive-number env override, falling back to `fallback` for anything
// missing, non-numeric, or ≤ 0. Without this, a typo'd value (e.g. MAX_GAIN=abc)
// becomes NaN and poisons the gain math — every sample rounds to 0 and the caller
// goes silent to STT. Coercing bad input to the safe default keeps a
// misconfiguration from silently breaking the whole call.
function agcNumber(raw: string | undefined, fallback: number): number {
  if (raw === undefined) return fallback;
  const n = Number(raw);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}
const INBOUND_AGC_ENABLED = process.env.STT_INBOUND_AGC !== "0";
// Target RMS for boosted speech (~-18 dBFS at 16-bit full scale) — loud enough to
// engage the STT VAD reliably, with headroom before the ceiling.
const INBOUND_AGC_TARGET_RMS = agcNumber(process.env.STT_INBOUND_AGC_TARGET_RMS, 4000);
// Hard cap on boost, regardless of how quiet the frame is — stops a near-silent
// line from being multiplied into amplified noise.
const INBOUND_AGC_MAX_GAIN = agcNumber(process.env.STT_INBOUND_AGC_MAX_GAIN, 12);
// Peak ceiling the boosted signal must never exceed (~-1 dBFS). The per-frame gain
// is limited so peak × gain ≤ this, so the output physically cannot clip.
const INBOUND_AGC_PEAK_CEILING = agcNumber(process.env.STT_INBOUND_AGC_PEAK_CEILING, 29000);
// Frames quieter than this RMS are treated as pure silence/hiss and held near 1×.
// Kept LOW so genuinely soft speech (RMS ~80–170 on a quiet handset) is still
// boosted rather than mistaken for hiss. Idle-line hiss sits well below this.
const INBOUND_AGC_NOISE_GATE_RMS = agcNumber(process.env.STT_INBOUND_AGC_NOISE_GATE_RMS, 55);

class InboundAgc {
  // Smoothed gain carried across frames so it adapts gradually (no pumping).
  private gain = 1;

  process(pcm: Buffer): Buffer {
    const sampleCount = pcm.length >> 1; // whole 16-bit LE samples
    if (sampleCount === 0) return pcm;

    // One pass for both loudness (RMS) and the clip limit (peak).
    let sumSq = 0;
    let peak = 1; // avoid divide-by-zero
    for (let i = 0; i < sampleCount; i++) {
      const s = pcm.readInt16LE(i << 1);
      sumSq += s * s;
      const a = s < 0 ? -s : s;
      if (a > peak) peak = a;
    }
    const rms = Math.sqrt(sumSq / sampleCount);

    // Gain that reaches the loudness target, but never enough to push this frame's
    // peak past the ceiling (no clipping), and never above the hard cap. Below the
    // noise floor, aim for unity so silence/hiss isn't amplified.
    const gainNoClip = INBOUND_AGC_PEAK_CEILING / peak;
    const desired =
      rms < INBOUND_AGC_NOISE_GATE_RMS
        ? 1
        : Math.max(1, Math.min(INBOUND_AGC_MAX_GAIN, INBOUND_AGC_TARGET_RMS / rms, gainNoClip));

    // Near-instant attack so the very first frames of a soft caller's onset are
    // already boosted — a slow ramp left the onset quiet and the STT VAD never
    // triggered, dropping the whole utterance. Slower release avoids yanking the
    // gain down between words.
    const coeff = desired > this.gain ? 0.9 : 0.15;
    this.gain += (desired - this.gain) * coeff;

    // Even after smoothing, never let THIS frame clip: cap the applied gain to the
    // frame's own no-clip limit.
    const applied = Math.min(this.gain, gainNoClip);
    if (applied <= 1.02) return pcm;

    const out = Buffer.allocUnsafe(sampleCount << 1);
    for (let i = 0; i < sampleCount; i++) {
      let v = Math.round(pcm.readInt16LE(i << 1) * applied);
      // Final safety clamp — should never trigger given the peak limit above.
      if (v > 32767) v = 32767;
      else if (v < -32768) v = -32768;
      out.writeInt16LE(v, i << 1);
    }
    return out;
  }
}

class PcmReframer {
  private buf: Buffer = Buffer.alloc(0);

  constructor(private readonly emit: (frame: Buffer) => void) {}

  push(chunk: Buffer) {
    if (chunk.length === 0) return;
    this.buf = this.buf.length ? Buffer.concat([this.buf, chunk]) : chunk;
    while (this.buf.length >= EXOTEL_FRAME_BYTES) {
      this.emit(this.buf.subarray(0, EXOTEL_FRAME_BYTES));
      this.buf = this.buf.subarray(EXOTEL_FRAME_BYTES);
    }
  }

  // Emit the remaining bytes, padded with PCM silence (0x00) to a 320-byte
  // multiple so Exotel accepts the final partial frame. Called once at the end
  // of a turn; on barge-in/cancel we drop the remainder instead.
  flush() {
    if (this.buf.length === 0) return;
    const remainder = this.buf.length % EXOTEL_FRAME_ALIGN;
    const frame =
      remainder === 0
        ? this.buf
        : Buffer.concat([this.buf, Buffer.alloc(EXOTEL_FRAME_ALIGN - remainder)]);
    this.emit(frame);
    this.buf = Buffer.alloc(0);
  }
}

// Drains queued audio frames to Exotel at ~real-time pace. Without this the
// whole reply is sent in one burst and Exotel drops it; see EXOTEL_FRAME_PACING_MS.
class PacedSender {
  private queue: Buffer[] = [];
  private timer: ReturnType<typeof setTimeout> | null = null;

  constructor(private readonly send: (frame: Buffer) => void) {}

  enqueue(frame: Buffer) {
    this.queue.push(frame);
    this.pump();
  }

  private pump() {
    if (this.timer) return;
    const next = () => {
      const frame = this.queue.shift();
      if (!frame) {
        this.timer = null;
        return;
      }
      this.send(frame);
      this.timer = setTimeout(next, EXOTEL_FRAME_PACING_MS);
    };
    next(); // first frame immediately, then paced
  }

  // Drop everything still queued — used on barge-in and teardown.
  clear() {
    this.queue = [];
    if (this.timer) {
      clearTimeout(this.timer);
      this.timer = null;
    }
  }

  // True while audio is still queued or in flight.
  get active(): boolean {
    return this.queue.length > 0 || this.timer !== null;
  }
}

type ActiveTurn = { controller: AbortController };

type SessionState = {
  callSid: string | null;
  callId: string | null;
  locale: string;
  turnIndex: number;
  stt: LiveSession | null;
  // Per-call inbound gain control — normalizes the caller's level before STT.
  agc: InboundAgc;
  // Serialises turn processing so overlapping utterances stay in order.
  queue: Promise<void>;
  speaking: boolean;
  active: ActiveTurn | null;
  // True only while the FINAL (end-call) statement is playing out. Barge-in is
  // disabled during this window so the caller saying "ok/bye" can't clip Maya's
  // closing line before the call hangs up.
  closing: boolean;
  // Real-time-paced audio sender to Exotel (shared across greeting + turns).
  pacer: PacedSender;
  // Inactivity: fires after INACTIVITY_TIMEOUT_MS with no client utterance.
  inactivityTimer: ReturnType<typeof setTimeout> | null;
  inactivityStrikes: number;
  // Timestamp of the last NOISE-only utterance (background chatter, the caller
  // speaking to someone else, line disturbance). Distinguishes a noisy/occupied
  // line from a genuinely silent one when the inactivity timer fires.
  lastNoiseAt: number;
  // When the current run of side-conversation turns began (0 = not in one). The
  // caller is speaking to a third party in clear sentences; after
  // SIDE_CONVERSATION_HANGUP_MS of it with no real reply, the call is ended.
  sideConversationSince: number;
  // True once the session is bound to a real `calls` row — only then can turns
  // persist and post-call processing run.
  hasDbRow: boolean;
  // True when THIS gateway created the row (an inbound / unmatched call with no
  // pre-existing record). It then owns marking the call completed + driving
  // post-call; a pre-existing row is instead managed by the status webhook.
  gatewayCreatedRow: boolean;
  // Guards finalizeCall so post-call is enqueued at most once per session.
  finalized: boolean;
  // Wall-clock start, for a best-effort durationSeconds on gateway-owned calls.
  startedAtMs: number;
};

// Exotel Voicebot WebSocket gateway.
//
// Exotel opens one WebSocket per call. Events from Exotel:
//   connected  → handshake complete
//   start      → stream begins; carries callSid + custom_parameters
//   media      → base64 linear16 8 kHz audio chunk
//   dtmf       → digit pressed by caller
//   stop       → caller hung up / stream ended
//
// This gateway sends back:
//   media      → base64 pcm_8000 (raw 16-bit linear PCM) audio for the reply
//   mark       → logical milestone (sentence boundary)
//   clear      → discard queued bot audio (barge-in)
@Injectable()
@WebSocketGateway({ path: "/exotel-stream" })
export class ExotelVoicebotGateway implements OnGatewayConnection, OnGatewayDisconnect {
  private readonly logger = new Logger("ExotelVoicebotGateway");
  private readonly sessions = new Map<WebSocket, SessionState>();

  constructor(
    private readonly deepgramLive: DeepgramLiveService,
    private readonly tts: ElevenlabsService,
    private readonly runtime: CallRuntimeService,
    @Inject(CallRepository) private readonly callRepo: CallRepository,
    private readonly postcallQueue: PostCallQueueService,
  ) {}

  handleConnection(client: WebSocket, request?: IncomingMessage) {
    // Optional shared-secret guard: set EXOTEL_STREAM_SECRET and include
    // ?token=<secret> in the WebSocket URL configured in the Exotel applet.
    // WebSocket-level auth: Exotel strips query params from wss:// URLs so a
    // shared-secret token in the URL is not reliable. Security is provided by:
    //   1. TLS (wss://) — connection is encrypted in transit
    //   2. callSid DB validation in the "start" event handler — any rogue
    //      connection that can't supply a valid callSid gets no useful response
    //   3. Exotel HMAC signature on all status-callback webhooks
    this.logger.log(`Exotel stream handshake — url=${request?.url ?? ""}`);

    const state: SessionState = {
      callSid: null,
      callId: null,
      locale: "hi-IN",
      turnIndex: 0,
      stt: null,
      agc: new InboundAgc(),
      queue: Promise.resolve(),
      speaking: false,
      active: null,
      closing: false,
      pacer: new PacedSender((frame) =>
        this.send(client, { event: "media", media: { payload: frame.toString("base64") } }),
      ),
      inactivityTimer: null,
      inactivityStrikes: 0,
      lastNoiseAt: 0,
      sideConversationSince: 0,
      hasDbRow: false,
      gatewayCreatedRow: false,
      finalized: false,
      startedAtMs: Date.now(),
    };
    this.sessions.set(client, state);
    this.logger.log("Exotel voicebot connection opened");

    client.on("message", (data: RawData) => {
      try {
        const msg = JSON.parse(data.toString()) as Record<string, unknown>;
        void this.handleEvent(client, state, msg);
      } catch {
        // Non-JSON frames are ignored.
      }
    });
  }

  handleDisconnect(client: WebSocket) {
    const state = this.sessions.get(client);
    if (state) {
      state.active?.controller.abort();
      state.stt?.close();
      state.pacer.clear();
      this.clearInactivityTimer(state);
      // The socket closing is the definitive end of the call (normal hang-up,
      // caller drop, or our own client.close() after end-call). Guarantee the
      // call reaches post-call processing → CRM. Fire-and-forget; runs once.
      void this.finalizeCall(state);
    }
    this.sessions.delete(client);
    this.logger.log(
      `Exotel voicebot disconnected${state?.callSid ? ` callSid=${state.callSid}` : ""}`,
    );
  }

  // Ensure a call the gateway handled reaches post-call processing (→ CRM). Both
  // inbound and outbound calls flow through this gateway, so it's the one place
  // that always knows a call happened. Runs at most once per session.
  //   - gatewayCreatedRow (inbound, no webhook manages it): mark the row
  //     completed and enqueue post-call immediately.
  //   - pre-existing row (outbound, webhook-managed): enqueue a DELAYED backstop
  //     so the `completed` webhook normally wins (shared jobId dedupes the two);
  //     if the webhook never fires, the backstop still delivers the call to CRM.
  //   - no DB row (couldn't create one): nothing to persist or process.
  private async finalizeCall(state: SessionState): Promise<void> {
    if (state.finalized || !state.hasDbRow || !state.callId) return;
    state.finalized = true;
    const callId = state.callId;

    if (state.gatewayCreatedRow) {
      try {
        const durationSeconds = Math.max(0, Math.round((Date.now() - state.startedAtMs) / 1000));
        await this.callRepo.update(callId, {
          status: "completed",
          endedAt: new Date(),
          durationSeconds,
        });
      } catch (err) {
        this.logger.warn(`Failed to mark gateway call completed callId=${callId}: ${String(err)}`);
      }
      try {
        await this.postcallQueue.enqueue(callId);
        this.logger.log(`Post-call enqueued (gateway-owned) callId=${callId}`);
      } catch (err) {
        this.logger.warn(`Failed to enqueue post-call callId=${callId}: ${String(err)}`);
      }
    } else {
      try {
        await this.postcallQueue.enqueue(callId, { delayMs: POSTCALL_BACKSTOP_DELAY_MS });
      } catch (err) {
        this.logger.warn(`Failed to enqueue post-call backstop callId=${callId}: ${String(err)}`);
      }
    }
  }

  private async handleEvent(client: WebSocket, state: SessionState, msg: Record<string, unknown>) {
    switch (String(msg.event ?? "")) {
      case "connected":
        this.logger.log("Exotel stream: connected");
        break;

      case "start": {
        const start = (msg.start ?? {}) as Record<string, unknown>;
        // Exotel sends either call_sid (newer) or callSid (older) field.
        const callSid = String(start.call_sid ?? start.callSid ?? "");
        const custom = (start.custom_parameters ?? start.customParameters ?? {}) as Record<
          string,
          string
        >;

        state.callSid = callSid || null;

        // Caller/callee numbers for the (inbound) row we may create below. Outbound
        // rows already carry these from the dial worker, but an inbound first-time
        // caller has no crm_lead_id, and the CRM rejects a phone-less new lead (422).
        // Capture whatever Exotel provides — natively on `start` or via applet
        // custom_parameters. The raw `start` is logged once per call so we can confirm
        // the exact field names this Exotel account sends and tighten this if needed.
        this.logger.log(`Exotel start payload: ${JSON.stringify(start)}`);
        const pickNumber = (...keys: string[]): string | null => {
          for (const key of keys) {
            const value = start[key] ?? (custom as Record<string, unknown>)[key];
            if (typeof value === "string" && value.trim()) return value.trim();
          }
          return null;
        };
        const fromNumber = pickNumber("from", "From", "CallFrom", "caller", "caller_id");
        const toNumber = pickNumber("to", "To", "CallTo", "called", "dialed_number");

        // Prefer callId passed explicitly via the applet's custom parameters so
        // we avoid an extra DB round-trip on every call. Fall back to a lookup
        // by Exotel's CallSid when no explicit mapping is provided.
        if (custom.callId) {
          state.callId = custom.callId;
          state.hasDbRow = true; // outbound: worker created the row; webhook manages it
          if (custom.locale) state.locale = custom.locale;
        } else if (callSid) {
          try {
            const call = await this.callRepo.findByProviderCallSid(callSid);
            if (call) {
              state.callId = call.id;
              state.hasDbRow = true;
              if (call.locale) state.locale = call.locale;
            }
          } catch (err) {
            this.logger.warn(`Failed to resolve callId from callSid=${callSid}: ${String(err)}`);
          }
        }

        if (!state.callId) {
          // No pre-existing calls row (an inbound call, or the applet didn't pass
          // a callId). Create one now so (a) call_turns persist against a real FK
          // and (b) post-call processing has a row to read — otherwise the call
          // never reaches the CRM. This gateway then owns finalizing it.
          if (callSid) {
            const newCall: NewCall = {
              providerCallSid: callSid,
              direction: "inbound",
              status: "in_progress",
              answeredAt: new Date(),
              locale: state.locale,
              fromNumber,
              toNumber,
            };
            try {
              const created = await this.callRepo.create(newCall);
              state.callId = created.id;
              state.hasDbRow = true;
              state.gatewayCreatedRow = true;
              this.logger.log(
                `Created calls row id=${created.id} for unmatched callSid=${callSid}`,
              );
            } catch (err) {
              // Most likely a unique-index race with the status webhook inserting
              // the same providerCallSid — re-fetch and adopt that row.
              const existing = await this.callRepo
                .findByProviderCallSid(callSid)
                .catch(() => undefined);
              if (existing) {
                state.callId = existing.id;
                state.hasDbRow = true;
                if (existing.locale) state.locale = existing.locale;
              } else {
                state.callId = callSid;
                this.logger.warn(
                  `Could not create/resolve calls row for callSid=${callSid}: ${String(err)} — turns won't persist`,
                );
              }
            }
          } else {
            state.callId = `exotel-${Date.now()}`;
            this.logger.warn(`No callSid on start — using ephemeral key=${state.callId}`);
          }
        }

        this.logger.log(
          `Exotel stream start: callSid=${callSid} callId=${state.callId} locale=${state.locale}`,
        );

        // Warm clip cache and fire opening greeting concurrently.
        void this.runtime.warmCall(state.callId, state.locale);
        void this.sendGreeting(client, state);

        state.stt = this.openSttSession(client, state);
        break;
      }

      case "media": {
        const payload = (msg.media as Record<string, unknown> | undefined)?.payload;
        if (typeof payload === "string" && state.stt) {
          const pcm = Buffer.from(payload, "base64");
          // Only boost when Maya is NOT audible — during her playback the caller's
          // line carries her own echo back (no echo cancellation), and amplifying
          // that would risk transcribing echo into a false barge-in. When it's the
          // caller's turn to speak, lift a soft-spoken caller toward a level STT
          // can reliably hear.
          const boost = INBOUND_AGC_ENABLED && !this.isMayaAudible(state);
          state.stt.sendAudio(boost ? state.agc.process(pcm) : pcm);
        }
        break;
      }

      case "dtmf": {
        const digit = String((msg.dtmf as Record<string, unknown> | undefined)?.digit ?? "");
        if (digit) {
          this.logger.log(`DTMF digit=${digit} callId=${state.callId}`);
          // DTMF locale selection can be wired here if needed.
        }
        break;
      }

      case "stop":
        this.logger.log(`Exotel stream stop: callId=${state.callId}`);
        state.active?.controller.abort();
        state.stt?.close();
        state.stt = null;
        state.pacer.clear();
        this.clearInactivityTimer(state);
        break;
    }
  }

  private async sendGreeting(client: WebSocket, state: SessionState): Promise<void> {
    if (!state.callId || client.readyState !== WebSocket.OPEN) return;

    const controller = new AbortController();
    state.active = { controller };

    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });

    try {
      const result = await this.runtime.generateGreetingStream(
        state.callId,
        state.locale,
        {
          signal: controller.signal,
          onAudioChunk: (chunk, info) => {
            if (chunk.length > 0) {
              reframer.push(chunk);
            } else if (info.last) {
              this.send(client, { event: "mark", mark: { name: `g${info.sentenceIndex}` } });
            }
          },
          onCancel: () => {
            state.speaking = false;
            state.pacer.clear();
            this.send(client, { event: "clear" });
          },
        },
        { outputFormat: EXOTEL_OUTPUT_FORMAT },
      );

      // Drain the final partial frame only on a clean finish; on barge-in the
      // remainder is intentionally dropped (we already sent "clear").
      if (!result.canceled && !controller.signal.aborted) {
        reframer.flush();
      }
      if (!result.skipped && !result.canceled) {
        state.speaking = false;
      }
    } catch (err) {
      this.logger.error(
        `Greeting failed callId=${state.callId}`,
        err instanceof Error ? err.stack : String(err),
      );
    } finally {
      if (state.active?.controller === controller) state.active = null;
      // Greeting done — start the 45 s inactivity clock waiting for client to speak.
      this.resetInactivityTimer(client, state);
    }
  }

  private openSttSession(client: WebSocket, state: SessionState): LiveSession {
    // NOTE: Deepgram's onSpeechStart (raw VAD) is intentionally NOT wired here.
    // It fires before any transcript and would barge-in on a single voiced frame
    // of echo/noise — exactly the self-interruption BARGE_IN_MIN_CHARS guards
    // against. Barge-in is driven by transcript partials (handlePartial) instead.
    return this.deepgramLive.openSession(
      state.locale,
      EXOTEL_SAMPLE_RATE,
      {
        onPartial: (text) => this.handlePartial(client, state, text),
        onUtterance: (text) => this.enqueueTurn(client, state, text),
        onError: (message) => {
          this.logger.warn(`STT error callId=${state.callId}: ${message}`);
        },
      },
      { encoding: "linear16" },
    );
  }

  // True while Maya's voice is still going out to the caller. CRUCIAL: a turn's
  // promise resolves when audio is handed to the pacer, NOT when Exotel finishes
  // playing it — the pacer keeps streaming for seconds afterwards. So `active`
  // and `speaking` are both false during that tail; only `pacer.active` reflects
  // that the caller can still hear Maya. Barge-in MUST consider it or late
  // interruptions are missed.
  private isMayaAudible(state: SessionState): boolean {
    return state.active !== null || state.speaking || state.pacer.active;
  }

  // Stop whatever Maya is currently saying: abort the in-flight turn, drop all
  // queued + in-flight audio locally, and tell Exotel to flush its own playback
  // buffer. After this the caller has the floor.
  private stopSpeaking(client: WebSocket, state: SessionState) {
    state.active?.controller.abort();
    state.pacer.clear();
    this.send(client, { event: "clear" });
    state.speaking = false;
  }

  // Server-side barge-in (fast path): the caller starts talking over Maya. The
  // BARGE_IN_MIN_CHARS floor filters 1-2 char noise/echo blips while still
  // catching short interjections ("हाँ", "रुको", "stop", "नहीं"). She goes silent
  // immediately and the completed utterance drives the next turn.
  private handlePartial(client: WebSocket, state: SessionState, text: string) {
    if (state.closing) return; // never interrupt the final closing line
    if (this.isMayaAudible(state) && text.trim().length >= BARGE_IN_MIN_CHARS) {
      this.logger.log(`Barge-in (partial) callId=${state.callId} — stopping playback`);
      this.stopSpeaking(client, state);
    }
  }

  private enqueueTurn(client: WebSocket, state: SessionState, utterance: string) {
    this.logger.log(`Utterance callId=${state.callId}: "${utterance.slice(0, 60)}"`);
    // Only a REAL utterance resets the inactivity clock. Pure noise/filler must
    // NOT — otherwise a noisy-but-dead line keeps re-arming the timer and never
    // reaches the goodbye. Instead we remember when noise last arrived so the
    // inactivity handler can tell a noisy/occupied line from a silent one.
    if (isNoisyTranscript(utterance)) {
      state.lastNoiseAt = Date.now();
    } else {
      state.inactivityStrikes = 0;
      state.lastNoiseAt = 0;
      // Follow the caller's language: once they clearly speak English (or Hindi),
      // switch the session locale so the inactivity check-in, goodbye, and reply
      // TTS all match them. Short/ambiguous acks return null and don't switch.
      const lang = detectSpokenLanguage(utterance);
      if (lang) {
        const target = lang === "hi" ? "hi-IN" : "en-IN";
        if (state.locale !== target) {
          this.logger.log(
            `Caller language=${lang} → session locale ${target} (callId=${state.callId})`,
          );
          state.locale = target;
        }
      }
      this.resetInactivityTimer(client, state);
    }
    // Reliable barge-in (commit path): a fully-formed caller utterance must stop
    // Maya even if no partial triggered the fast path above — otherwise her old
    // reply keeps playing from the pacer/Exotel buffer and this turn just queues
    // behind it (the bug that made barge-in look broken). Skipped while closing.
    if (!state.closing && this.isMayaAudible(state)) {
      this.logger.log(`Barge-in (utterance) callId=${state.callId} — stopping playback`);
      this.stopSpeaking(client, state);
    }
    state.queue = state.queue.then(async () => {
      if (!state.callId || client.readyState !== WebSocket.OPEN) return;
      await this.runTurn(client, state, utterance);
    });
  }

  private async runTurn(client: WebSocket, state: SessionState, utterance: string) {
    const controller = new AbortController();
    const active: ActiveTurn = { controller };
    state.active = active;
    state.speaking = false;

    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });

    try {
      const result = await this.runtime.processUtteranceStream(
        state.callId!,
        state.turnIndex,
        utterance,
        { locale: state.locale, outputFormat: EXOTEL_OUTPUT_FORMAT },
        {
          signal: controller.signal,
          onAudioChunk: (chunk, info) => {
            if (chunk.length > 0) {
              reframer.push(chunk);
            } else if (info.last) {
              // Sentence boundary — let Exotel track playback progress.
              this.send(client, { event: "mark", mark: { name: `s${info.sentenceIndex}` } });
            }
          },
          onCancel: () => {
            state.speaking = false;
            state.pacer.clear();
            this.send(client, { event: "clear" });
          },
          onEndCall: () => {
            // Lock out barge-in the moment the LLM signals end-call, before TTS
            // audio finishes draining — otherwise a 1-char partial from background
            // noise fires stopSpeaking and clips Maya's closing statement.
            state.closing = true;
          },
        },
      );

      // Drain the final partial frame only on a clean finish; on barge-in the
      // remainder is intentionally dropped (we already sent "clear").
      if (!result.canceled && !controller.signal.aborted) {
        reframer.flush();
      }

      if (!result.waitForMore && !result.canceled) {
        state.stt?.clearBuffer();
        state.turnIndex += 1;
      }

      // Side-conversation escape: the caller is talking to a third party, not to
      // Maya (she stayed silent this turn). Give it one SIDE_CONVERSATION_HANGUP_MS
      // window; if side chatter is still going with no real reply, bow out and
      // hang up. Any genuine reply below resets the window.
      if (result.sideConversation) {
        const now = Date.now();
        if (state.sideConversationSince === 0) {
          state.sideConversationSince = now;
          this.logger.log(
            `Side conversation started callId=${state.callId} — ${SIDE_CONVERSATION_HANGUP_MS}ms escape window`,
          );
        } else if (now - state.sideConversationSince >= SIDE_CONVERSATION_HANGUP_MS && !state.closing) {
          this.logger.log(`Side conversation exceeded window callId=${state.callId} — hanging up`);
          state.closing = true;
          const isHindi = state.locale.startsWith("hi") || state.locale.startsWith("gu");
          const goodbye = isHindi
            ? "कोई बात नहीं, लगता है आप अभी थोड़ा busy हैं। हमारे sales expert आपसे personally connect करेंगे। Thank you."
            : "No problem, it seems you're a little busy right now. Our sales expert will personally reach out to you. Thank you.";
          await this.playDirectTts(state, goodbye);
          await this.waitForPacerDrain(state, 10_000);
          await new Promise<void>((r) => setTimeout(r, EXOTEL_HANGUP_GRACE_MS));
          try {
            client.close();
          } catch {}
        }
      } else if (!result.canceled && !isNoisyTranscript(utterance)) {
        // A real reply (or a mid-thought fragment-hold) — reset the escape window.
        state.sideConversationSince = 0;
      }

      if (result.endCall) {
        // Lock out barge-in so a caller "ok/bye/thanks" during the closing line
        // can't abort it and hang up mid-sentence.
        state.closing = true;
        this.logger.log(`Call ended callId=${state.callId} — draining final audio`);
        // Let the paced audio fully drain before closing the WebSocket, else
        // the final reply is cut off. Cap the wait so a stuck pacer can't hang.
        await this.waitForPacerDrain(state, 20_000);
        // Our local queue drains slightly ahead of real-time playback, so give
        // Exotel's buffer time to finish playing Maya's last sentence before we
        // hang up — otherwise her closing line gets clipped.
        await new Promise<void>((r) => setTimeout(r, EXOTEL_HANGUP_GRACE_MS));
        try {
          client.close();
        } catch {}
      }
    } catch (err) {
      this.logger.error(
        `Turn failed callId=${state.callId}`,
        err instanceof Error ? err.stack : String(err),
      );
    } finally {
      if (state.active === active) state.active = null;
      // Always clear: on clean finish we never set it false otherwise; on barge-in
      // onCancel already did this, so setting false twice is harmless.
      state.speaking = false;
    }
  }

  // Resolve once the paced sender has flushed all queued audio, or after
  // maxWaitMs as a safety cap so a stalled pacer can never hang call teardown.
  private async waitForPacerDrain(state: SessionState, maxWaitMs: number): Promise<void> {
    const deadline = Date.now() + maxWaitMs;
    while (state.pacer.active && Date.now() < deadline) {
      await new Promise<void>((r) => setTimeout(r, EXOTEL_FRAME_PACING_MS));
    }
  }

  private send(client: WebSocket, payload: Record<string, unknown>) {
    if (client.readyState === WebSocket.OPEN) {
      try {
        client.send(JSON.stringify(payload));
      } catch {}
    }
  }

  private resetInactivityTimer(client: WebSocket, state: SessionState): void {
    if (state.inactivityTimer !== null) {
      clearTimeout(state.inactivityTimer);
      state.inactivityTimer = null;
    }
    if (state.closing) return;
    state.inactivityTimer = setTimeout(
      () => void this.handleInactivity(client, state),
      INACTIVITY_TIMEOUT_MS,
    );
  }

  private clearInactivityTimer(state: SessionState): void {
    if (state.inactivityTimer !== null) {
      clearTimeout(state.inactivityTimer);
      state.inactivityTimer = null;
    }
  }

  private handleInactivity(client: WebSocket, state: SessionState): void {
    state.inactivityTimer = null;
    if (state.closing || client.readyState !== WebSocket.OPEN) return;
    if (this.isMayaAudible(state)) {
      // Maya is mid-reply — re-arm and check again shortly.
      state.inactivityTimer = setTimeout(
        () => void this.handleInactivity(client, state),
        2_000,
      );
      return;
    }
    const isHindi = state.locale.startsWith("hi") || state.locale.startsWith("gu");
    // Noisy line / caller talking to someone else: audio has been arriving (noise
    // utterances) for the whole window but none of it was a real reply to Maya.
    // Don't keep the line open or bother with a check-in — after this single 35s
    // window, say a brief goodbye and hang up. A genuinely SILENT line (no noise)
    // still gets the gentle "are you still there?" nudge first.
    const noisyWindow =
      state.lastNoiseAt > 0 && Date.now() - state.lastNoiseAt < INACTIVITY_TIMEOUT_MS;
    if (noisyWindow) {
      state.inactivityStrikes = INACTIVITY_MAX_STRIKES;
    } else {
      state.inactivityStrikes += 1;
    }
    const strikes = state.inactivityStrikes;

    if (strikes >= INACTIVITY_MAX_STRIKES) {
      // Final strike (or a noisy/occupied line) — say goodbye and hang up. Include
      // the AI-disclosure line so this system-driven ending matches a normal sign-off.
      const goodbye = noisyWindow
        ? isHindi
          ? "लगता है line पर कुछ disturbance है या आप अभी busy हैं। हमारे sales expert आपसे personally connect करेंगे। Thank you."
          : "It seems the line is disturbed or you're occupied right now. Our sales expert will personally reach out to you. Thank you."
        : isHindi
          ? "लगता है आप अभी available नहीं हैं। हमारे sales expert आपसे personally connect करेंगे। Thank you."
          : "It seems you are unavailable. Our sales expert will personally reach out to you. Thank you.";
      state.queue = state.queue.then(async () => {
        // A real utterance arriving in the meantime resets inactivityStrikes to 0,
        // cancelling this hangup; continued noise leaves strikes at the max.
        if (state.inactivityStrikes < strikes || client.readyState !== WebSocket.OPEN) return;
        state.closing = true;
        await this.playDirectTts(state, goodbye);
        await this.waitForPacerDrain(state, 10_000);
        await new Promise<void>((r) => setTimeout(r, EXOTEL_HANGUP_GRACE_MS));
        try { client.close(); } catch {}
      });
    } else {
      // First strike on a silent line — ask if they're still there.
      const checkIn = isHindi
        ? "Hello? क्या आप अभी भी line पर हैं?"
        : "Hello? Are you still there?";
      state.queue = state.queue.then(async () => {
        // If the client spoke while this was queued, skip it.
        if (state.inactivityStrikes < strikes || state.closing) return;
        if (client.readyState !== WebSocket.OPEN) return;
        await this.playDirectTts(state, checkIn);
      });
      // Re-arm: another INACTIVITY_TIMEOUT_MS with no response → second strike.
      this.resetInactivityTimer(client, state);
    }
  }

  // Synthesize text directly to the pacer, bypassing the LLM pipeline.
  // Used for inactivity check-ins where no LLM call is needed.
  private async playDirectTts(state: SessionState, text: string): Promise<void> {
    const controller = new AbortController();
    state.active = { controller };
    state.speaking = false;
    const reframer = new PcmReframer((frame) => {
      state.speaking = true;
      state.pacer.enqueue(frame);
    });
    try {
      await this.tts.synthesizeStream(text, {
        languageCode: /[ऀ-ॿ]/.test(text) ? undefined : "en",
        outputFormat: EXOTEL_OUTPUT_FORMAT,
        signal: controller.signal,
        onChunk: (chunk) => {
          if (chunk.length > 0) reframer.push(chunk);
        },
      });
      if (!controller.signal.aborted) reframer.flush();
    } catch {
      // aborted by barge-in or TTS failure — pacer carries whatever was queued
    } finally {
      state.speaking = false;
      if (state.active?.controller === controller) state.active = null;
    }
  }
}
